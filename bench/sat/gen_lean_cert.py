#!/usr/bin/env python3
"""
Writes a Lean file containing the base CNF and the (expanded) resolution
certificate, for checking with `lean/Resolution.lean`.

Usage: python3 gen_lean_cert.py --problem s3 --proof proof_s3.rup \
                               --lean ../../lean/CertificateS3.lean --name 3
"""
import argparse
import sys

import cdcl45
import expand_resolution as ex


def lit_lean(l):
    return f"({abs(l)}, {'true' if l > 0 else 'false'})"


def clause_lean(c):
    return "[" + ", ".join(lit_lean(l) for l in c) + "]"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--problem", choices=["s3", "s4"], default="s3")
    ap.add_argument("--proof", required=True)
    ap.add_argument("--sym", action="store_true")
    ap.add_argument("--lean", required=True)
    ap.add_argument("--name", required=True)
    args = ap.parse_args()

    if args.problem == "s3":
        base, _ = cdcl45.build_cnf_s3()
    else:
        base = cdcl45.build_cnf(args.sym)
    proof = ex.read_proof(args.proof)
    expanded, err = ex.expand(base, proof)
    if err:
        sys.exit("expansion FAILED: " + err)
    err = ex.verify(base, expanded)
    if err:
        sys.exit("verification FAILED: " + err)

    name = args.name
    with open(args.lean, "w", encoding="utf-8") as f:
        f.write("import Resolution\n\n")
        f.write("set_option maxRecDepth 1000000\n")
        f.write("set_option maxHeartbeats 0\n\n")
        f.write("/-! Generated by `bench/sat/gen_lean_cert.py` — do not edit.\n\n")
        f.write("The base CNF is exactly the one built by `bench/sat/cdcl45.py`;\n")
        f.write("the derivation was expanded from the RUP certificate and already\n")
        f.write("checked by an independent Python implementation.  Lean re-checks it\n")
        f.write("with the proved checker `Resolution.checkProof_sound`.\n-/\n\n")
        f.write("namespace Resolution\n\n")
        f.write(f"def base{name} : CNF :=\n  [\n")
        f.write(",\n".join("    " + clause_lean(c) for c in base))
        f.write("\n  ]\n\n")
        f.write(f"def steps{name} : List (Clause × Justify) :=\n  [\n")
        rows = []
        for C, j in expanded:
            if j[0] == "resolve":
                _, a, b, v = j
                rows.append(f"    ({clause_lean(C)}, .resolve {a} {b} {v})")
            else:
                _, a = j
                rows.append(f"    ({clause_lean(C)}, .weaken {a})")
        f.write(",\n".join(rows))
        f.write(f"\n  ]\n\n")
        f.write(f"def cert{name} : Cert := {{ base := base{name}, steps := steps{name} }}\n\n")
        f.write("end Resolution\n")
    print(f"wrote {args.lean}: base {len(base)} clauses, {len(expanded)} steps",
          file=sys.stderr)


if __name__ == "__main__":
    main()
